"""Export SPICE assets for every simulated sheet, and precompute default results."""
import sys, os, re, json, zipfile, io, time
from playwright.sync_api import sync_playwright
REPO, COMET = sys.argv[1], sys.argv[2]
PORT = sys.argv[3] if len(sys.argv) > 3 else "8790"                       # local server for the built index.html
VAL = sys.argv[4] if len(sys.argv) > 4 else os.path.join(COMET, "..", "..", "export")   # unpacked copies for validation
P = lambda *a: print(*a, flush=True)
README = """COMET - {title} (DWG {dwg})
LTspice schematic generated from the COMET system schematic
https://ahmeteminaydin.github.io/comet/

Open it
  1. Extract ALL files into one folder (do not open them from inside the zip).
  2. Open {name}.asc in LTspice and press Run.
  3. Click a wire to plot its voltage; right-click a part to change its value.

Files
  {name}.asc         the schematic, same circuit and values as the site
  *.asy              symbols for the parts LTspice does not ship
  comet_models.lib   behavioural models (op-amps, comparator, logic, SiPM, ...)

The text block under the schematic is the test bench: it drives the input
ports the same way the site does. The models are simplified stand-ins; see the
comments at the top of comet_models.lib.
{extra}"""
with sync_playwright() as pw:
    b = pw.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
    pg = b.new_page(viewport={"width":1300,"height":900}); errs = []
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto(f"http://127.0.0.1:{PORT}/index.html", wait_until="domcontentloaded"); pg.wait_for_timeout(400)
    ids = pg.evaluate("Object.keys(SIMCFG)")
    pre = {}
    pg.evaluate("spiceEngine()")
    for id in ids:
        r = pg.evaluate(f"(() => {{ const x = spiceAsc('{id}'); return {{asc:x.asc, files:x.files, lib:x.lib, cir:x.cir, title:SHEETS['{id}'].title, dwg:SHEETS['{id}'].dwg, excl:SIMCFG['{id}'].exclude||[], why:SIMCFG['{id}'].excludeWhy||''}}; }})()")
        name = f"COMET_{id.upper()}"; d = os.path.join(REPO, "sim", id); os.makedirs(d, exist_ok=True)
        cir = re.sub(r"\n\.end\s*$", lambda m: "\n* ngspice: ngspice " + name + ".cir, then type run and plot v(<net>)\n* LTspice: open this file and press Run\n.end\n", r["cir"])
        open(os.path.join(d, name + ".cir"), "w", newline="\n").write(cir)
        extra = (f"\nNot simulated: {', '.join(r['excl'])} ({r['why']}).\n") if r["excl"] else ""
        zb = io.BytesIO()
        with zipfile.ZipFile(zb, "w", zipfile.ZIP_DEFLATED) as z:
            z.writestr(name + ".asc", r["asc"])
            for fn, txt in sorted(r["files"].items()): z.writestr(fn, txt)
            z.writestr("comet_models.lib", r["lib"].replace("\n", "\r\n"))
            z.writestr("README.txt", README.format(title=r["title"], dwg=r["dwg"], name=name, extra=extra).replace("\n", "\r\n"))
        open(os.path.join(d, name + "_LTspice.zip"), "wb").write(zb.getvalue())
        # unpacked copy for validation
        vd = os.path.join(VAL, id); os.makedirs(vd, exist_ok=True)
        with zipfile.ZipFile(io.BytesIO(zb.getvalue())) as z: z.extractall(vd)
        open(os.path.join(vd, name + ".cir"), "w").write(cir)
        # precomputed default results
        nana = pg.evaluate(f"SIMCFG['{id}'].analyses.length"); pre[id] = {}
        for ai in range(nana):
            res = pg.evaluate(f"""async () => {{
              const b = spiceBuild('{id}', {{analysis:{ai}}}), {{r}} = await spiceRun(b.text), D = spParse(r, b), names = Object.keys(D);
              const t = D[names[0]].t, n = t.length, keep = new Set([0, n - 1]), NB = 260;
              if (n > 900) names.forEach(nm => {{ const v = D[nm].v; for (let k = 0; k < NB; k++) {{ const a = Math.floor(k*n/NB), z = Math.max(a + 1, Math.floor((k + 1)*n/NB)); let lo = a, hi = a;
                  for (let i = a; i < z; i++) {{ if (v[i] < v[lo]) lo = i; if (v[i] > v[hi]) hi = i; }} keep.add(lo); keep.add(hi); }} }});
              else for (let i = 0; i < n; i++) keep.add(i);
              const idx = [...keep].sort((a, c) => a - c), f = x => +x.toPrecision(5);
              const out = {{t: idx.map(i => f(t[i])), v: {{}}}}; names.forEach(nm => out.v[nm] = idx.map(i => f(D[nm].v[i])));
              return out; }}""")
            aid = pg.evaluate(f"SIMCFG['{id}'].analyses[{ai}].id")
            pre[id][aid] = res
            P(f"{id:8s} {aid:4s} exported, precomputed {len(res['t'])} points x {len(res['v'])} probes")
    P("page errors:", errs[:3])
    b.close()
js = "\n/* ---------- SPICE: results precomputed with the design values (generated by export.py) ---------- */\nconst SPICE_PRE = " + json.dumps(pre, separators=(",", ":")) + ";\n"
open(os.path.join(COMET, "spice_pre.js"), "w").write(js)
P("spice_pre.js", len(js)//1024, "KB")
